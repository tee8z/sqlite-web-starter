use std::{
    env,
    error::Error,
    fmt::Write as _,
    fs,
    io::{self, Write as _},
    path::{Path, PathBuf},
};

use flate2::{Compression, write::GzEncoder};
use lightningcss::stylesheet::{MinifyOptions, ParserOptions, PrinterOptions, StyleSheet};
use minify_js::{Session, TopLevelMode, minify};
use sha2::{Digest, Sha256};

/// htmx and Bulma as published on npm (see the README beside each).
const HTMX: &str = "vendor/htmx/4.0.0/htmx.min.js";
const BULMA: &str = "vendor/bulma/1.0.2/bulma.min.css";

const CSS: &str = "text/css; charset=utf-8";
const JAVASCRIPT: &str = "text/javascript; charset=utf-8";

struct Asset {
    constant: &'static str,
    stem: &'static str,
    extension: &'static str,
    content_type: &'static str,
    bytes: Vec<u8>,
}

fn main() -> Result<(), Box<dyn Error>> {
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-changed=migrations");
    println!("cargo::rerun-if-changed=src/dashboard");
    println!("cargo::rerun-if-changed=vendor");

    let manifest = env::var_os("CARGO_MANIFEST_DIR").ok_or("CARGO_MANIFEST_DIR is missing")?;
    let output = env::var_os("OUT_DIR").ok_or("OUT_DIR is missing")?;
    let root = Path::new(&manifest);
    let output = Path::new(&output);
    let dashboard = root.join("src/dashboard");

    // Components keep their styles and scripts beside the Rust that renders them.
    let mut css_files = Vec::new();
    let mut js_files = Vec::new();
    collect_assets(&dashboard, &mut css_files, &mut js_files)?;
    let base_styles = dashboard.join("styles.css");
    css_files
        .sort_by(|left, right| (left != &base_styles, left).cmp(&(right != &base_styles, right)));
    js_files.sort();

    let css = concatenate_assets(&css_files, "\n")?;
    let mut stylesheet = StyleSheet::parse(
        &css,
        ParserOptions {
            filename: "src/dashboard (combined CSS)".into(),
            ..ParserOptions::default()
        },
    )
    .map_err(|error| io::Error::other(format!("parse CSS: {error}")))?;
    stylesheet
        .minify(MinifyOptions::default())
        .map_err(|error| io::Error::other(format!("minify CSS: {error}")))?;
    let css = stylesheet
        .to_css(PrinterOptions {
            minify: true,
            ..PrinterOptions::default()
        })?
        .code;

    // Newlines end trailing line comments; semicolons separate standalone scripts.
    let javascript = concatenate_assets(&js_files, "\n;\n")?;
    let session = Session::new();
    let mut js = Vec::new();
    // The page loads a classic deferred script, so preserve global-script semantics.
    minify(
        &session,
        TopLevelMode::Global,
        javascript.as_bytes(),
        &mut js,
    )
    .map_err(|error| io::Error::other(format!("minify src/dashboard JavaScript: {error:?}")))?;

    // The libraries are embedded as published; only this site's files are minified.
    let assets = [
        Asset {
            constant: "BULMA_CSS",
            stem: "bulma",
            extension: "css",
            content_type: CSS,
            bytes: fs::read(root.join(BULMA))?,
        },
        Asset {
            constant: "SITE_CSS",
            stem: "site",
            extension: "css",
            content_type: CSS,
            bytes: css.into_bytes(),
        },
        Asset {
            constant: "HTMX_JS",
            stem: "htmx",
            extension: "js",
            content_type: JAVASCRIPT,
            bytes: fs::read(root.join(HTMX))?,
        },
        Asset {
            constant: "SITE_JS",
            stem: "site",
            extension: "js",
            content_type: JAVASCRIPT,
            bytes: js,
        },
    ];

    let mut generated = String::from(
        "// Generated by build.rs; edit styles and scripts in src/dashboard/ instead.\n",
    );
    for asset in &assets {
        // Only Cargo's output directory contains generated files. The binary embeds them.
        let file = format!("{}.{}", asset.stem, asset.extension);
        fs::write(output.join(&file), &asset.bytes)?;
        fs::write(output.join(format!("{file}.gz")), gzip(&asset.bytes)?)?;
        let digest = Sha256::digest(&asset.bytes);
        let url = format!("/assets/{}.{digest:x}.{}", asset.stem, asset.extension);
        writeln!(
            generated,
            "pub const {constant}: Asset = Asset {{ url: {url:?}, content_type: {content_type:?}, \
             bytes: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{file}\")), \
             gzip: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{file}.gz\")) }};",
            constant = asset.constant,
            content_type = asset.content_type,
        )?;
    }
    let constants: Vec<_> = assets.iter().map(|asset| asset.constant).collect();
    writeln!(
        generated,
        "pub const ALL: &[Asset] = &[{}];",
        constants.join(", ")
    )?;
    fs::write(output.join("assets.rs"), generated)?;
    Ok(())
}

fn collect_assets(
    directory: &Path,
    css: &mut Vec<PathBuf>,
    javascript: &mut Vec<PathBuf>,
) -> io::Result<()> {
    for entry in fs::read_dir(directory)? {
        let entry = entry?;
        let file_type = entry.file_type()?;
        let path = entry.path();
        if file_type.is_dir() {
            collect_assets(&path, css, javascript)?;
        } else if file_type.is_file() {
            match path.extension().and_then(|extension| extension.to_str()) {
                Some("css") => css.push(path),
                Some("js") => javascript.push(path),
                _ => {}
            }
        }
    }
    Ok(())
}

fn concatenate_assets(files: &[PathBuf], separator: &str) -> io::Result<String> {
    let mut combined = String::new();
    for path in files {
        let source = fs::read_to_string(path).map_err(|error| {
            io::Error::new(error.kind(), format!("read {}: {error}", path.display()))
        })?;
        combined.push_str(&source);
        combined.push_str(separator);
    }
    Ok(combined)
}

fn gzip(bytes: &[u8]) -> io::Result<Vec<u8>> {
    let mut encoder = GzEncoder::new(Vec::new(), Compression::best());
    encoder.write_all(bytes)?;
    encoder.finish()
}
